"""
Plot PPO evaluation results from the Excel generated by parse_eval_to_excel.py.
Metrics are shown easy → hard for thesis presentation.

Usage:
    python plot_eval_results.py <eval_results.xlsx> [output_prefix]

Example:
    python plot_eval_results.py eval_results.xlsx thesis_fig
    → saves thesis_fig_by_metric.png  thesis_fig_by_object.png
"""

import sys
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

OBJECTS = ["mug", "drill", "dumbbell"]

# Easy → hard order
METRICS = [
    ("Phase2 Entry Rate",    "Phase2\nEntry Rate",    "#4C72B0"),
    ("Tight Contact Rate",   "Tight\nContact Rate",   "#55A868"),
    ("Partial Success Rate", "Partial\nSuccess Rate", "#DD8452"),
]

METRIC_DESC = {
    "Phase2 Entry Rate":    "Phase2 Entry Rate\n(Object Grasped & Transport Started)",
    "Tight Contact Rate":   "Tight Contact Rate\n(XY < 5 cm, |ΔZ| < 2 cm)",
    "Partial Success Rate": "Partial Success Rate\n(XY < 5 cm, ΔZ ∈ [−2, +1] cm)",
}


def load_excel(path: str) -> dict:
    xf  = pd.ExcelFile(path)
    return {
        sheet: xf.parse(sheet)
        for sheet in xf.sheet_names
        if sheet != "Summary"
    }


# ── Figure 1: One chart per metric, X = object ───────────────────────────────
def plot_by_metric(data: dict, out_path: str, model_name: str = "PPO"):
    fig, axes = plt.subplots(1, 3, figsize=(13, 5), sharey=True)

    for ax, (metric_name, metric_label, color) in zip(axes, METRICS):
        if metric_name not in data:
            ax.axis("off")
            continue

        df   = data[metric_name]
        df   = df[df["Object"] != "Average"].reset_index(drop=True)
        x    = np.arange(len(OBJECTS))
        mean = df["Mean (%)"].values
        std  = df["Std (%)"].values

        bars = ax.bar(x, mean, 0.55, yerr=std, color=color,
                      capsize=6, error_kw={"linewidth": 1.8},
                      alpha=0.88, edgecolor="white", linewidth=0.5)

        # Value labels on bars
        for bar, m in zip(bars, mean):
            if not np.isnan(m):
                ax.text(bar.get_x() + bar.get_width() / 2,
                        bar.get_height() + std[list(mean).index(m)] + 1.5,
                        f"{m:.1f}%", ha="center", va="bottom", fontsize=9,
                        fontweight="bold", color="dimgray")

        ax.set_title(METRIC_DESC[metric_name], fontsize=10, fontweight="bold",
                     pad=10, color="#333333")
        ax.set_xticks(x)
        ax.set_xticklabels(OBJECTS, fontsize=11)
        ax.set_ylim(0, 105)
        ax.set_ylabel("Rate (%)", fontsize=11)
        ax.yaxis.grid(True, alpha=0.35, linestyle="--")
        ax.set_axisbelow(True)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

    # Difficulty arrow annotation
    fig.text(0.13, -0.02,
             "← Easier", ha="left", fontsize=10, color="gray", style="italic")
    fig.text(0.87, -0.02,
             "Harder →", ha="right", fontsize=10, color="gray", style="italic")

    plt.suptitle(f"{model_name} Evaluation Results by Object  (Mean ± Std, 3 seeds)",
                 fontsize=13, fontweight="bold", y=1.03)
    plt.tight_layout()
    plt.savefig(out_path, dpi=200, bbox_inches="tight")
    print(f"Saved → {out_path}")
    plt.close()


# ── Figure 2: One chart per object, X = metric (easy → hard) ─────────────────
def plot_by_object(data: dict, out_path: str, model_name: str = "PPO"):
    fig, axes = plt.subplots(1, 3, figsize=(13, 5), sharey=True)
    colors = [c for _, _, c in METRICS]
    labels = [l.replace("\n", " ") for _, l, _ in METRICS]

    for ax, obj in zip(axes, OBJECTS):
        means, stds = [], []
        for metric_name, _, _ in METRICS:
            if metric_name in data:
                df  = data[metric_name]
                row = df[df["Object"] == obj]
                if not row.empty:
                    means.append(row["Mean (%)"].values[0])
                    stds.append(row["Std (%)"].values[0])
                else:
                    means.append(float("nan"))
                    stds.append(0)
            else:
                means.append(float("nan"))
                stds.append(0)

        x    = np.arange(len(METRICS))
        bars = ax.bar(x, means, 0.55, yerr=stds, color=colors,
                      capsize=6, error_kw={"linewidth": 1.8},
                      alpha=0.88, edgecolor="white", linewidth=0.5)

        for bar, m, s in zip(bars, means, stds):
            if not np.isnan(m):
                ax.text(bar.get_x() + bar.get_width() / 2,
                        m + s + 1.5,
                        f"{m:.1f}%", ha="center", va="bottom",
                        fontsize=9, fontweight="bold", color="dimgray")

        ax.set_title(obj.capitalize(), fontsize=13, fontweight="bold",
                     color="#333333")
        ax.set_xticks(x)
        ax.set_xticklabels(labels, fontsize=9)
        ax.set_ylim(0, 105)
        ax.set_ylabel("Rate (%)", fontsize=11)
        ax.yaxis.grid(True, alpha=0.35, linestyle="--")
        ax.set_axisbelow(True)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

    # Legend for metric colors
    handles = [
        plt.Rectangle((0, 0), 1, 1, color=c, alpha=0.88)
        for _, _, c in METRICS
    ]
    metric_labels = [n for n, _, _ in METRICS]
    fig.legend(handles, metric_labels, loc="lower center", ncol=3,
               fontsize=10, frameon=False, bbox_to_anchor=(0.5, -0.08))

    fig.text(0.13, -0.04, "← Easier", ha="left",
             fontsize=10, color="gray", style="italic")
    fig.text(0.87, -0.04, "Harder →", ha="right",
             fontsize=10, color="gray", style="italic")

    plt.suptitle(f"{model_name} Evaluation Results by Object  (Metrics ordered: Easy → Hard)",
                 fontsize=13, fontweight="bold", y=1.03)
    plt.tight_layout()
    plt.savefig(out_path, dpi=200, bbox_inches="tight")
    print(f"Saved → {out_path}")
    plt.close()


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    xlsx       = sys.argv[1]
    prefix     = sys.argv[2] if len(sys.argv) > 2 else "thesis_fig"
    model_name = sys.argv[3] if len(sys.argv) > 3 else "PPO"

    data = load_excel(xlsx)

    plot_by_metric(data, f"{prefix}_by_metric.png", model_name)
    plot_by_object(data, f"{prefix}_by_object.png", model_name)

    print("\nDone.")


if __name__ == "__main__":
    main()
